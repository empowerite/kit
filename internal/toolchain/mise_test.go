// locked4 is one entry of mise.lock, locked for each of the four platforms, as mise's aqua: entries are.
func locked4(name, version, backend string) string {
	text := "[[tools." + quoteKey(name) + "]]\nversion = \"" + version + "\"\nbackend = \"" + backend + "\"\n\n"
	for _, p := range []string{"linux-arm64", "linux-x64", "macos-arm64", "macos-x64"} {
		text += "[tools." + quoteKey(name) + ".\"platforms." + p + "\"]\nchecksum = \"sha256:" + strings.Repeat("a", 64) +
			"\"\nurl = \"https://example.com/" + name + "-" + p + ".tar.gz\"\n\n"
	}
	return text
}

func quoteKey(name string) string {
	if strings.ContainsAny(name, ":/") {
		return "\"" + name + "\""
	}
	return name
}

