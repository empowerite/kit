func TestCheckMiseFindsInfrastructuresFourEntriesWithNoDigest(t *testing.T) {
	found, err := CheckMise([]byte(infraToml), []byte(infraLock), true)
	want := []string{
		"npm:bats 1.13.0 has a version and no digest",
		"npm:markdownlint-cli2 0.23.1 has a version and no digest",
		"npm:wrangler 3.80.1 has a version and no digest",
		"ubi:terror/just-lsp 0.4.8 has a version and no digest",
	}
	if err != nil || !reflect.DeepEqual(whats(found), want) {
		t.Fatalf("CheckMise found %q, %v; want %q", whats(found), err, want)
	}
	if !strings.Contains(found[0].Fix, "package-lock.json") || !strings.Contains(found[0].Why, "chooses its dependencies") {
		t.Errorf("the npm: finding is %+v", found[0])
	}
	if !strings.Contains(found[3].Fix, "aqua:") || found[3].Where != "mise.lock" {
		t.Errorf("the ubi: finding is %+v", found[3])
	}
}

